export async function createIncident(data: Partial<IncidentItem>): Promise<IncidentItem> {
  try {
    const res = await fetch(`${BASE_URL}/incidents`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(data)
    });
    if (res.ok) return await res.json();
  } catch (e) {}
  return {
    id: `INC-${Math.floor(Math.random() * 899999 + 100000)}`,
    created_at: new Date().toISOString().replace('T', ' ').slice(0, 19),
    title: data.title || 'New Incident',
    location: data.location || 'Gate B',
    risk_level: data.risk_level || 'HIGH',
    risk_score: data.risk_score || 78,
    detected_factors: data.detected_factors || ['High Density'],
    duration: '0s',
    operator_notes: data.operator_notes || '',
    status: 'Open',
    timeline: [{ time: new Date().toLocaleTimeString(), event: 'Incident created', actor: 'Operator 1' }]
  };
}

export async function updateIncidentStatus(id: string, status: string, notes?: string): Promise<any> {
  try {
    const res = await fetch(`${BASE_URL}/incidents/${id}/status`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ status, operator_notes: notes })
    });
    if (res.ok) return await res.json();
  } catch (e) {}
  return { status };
}

